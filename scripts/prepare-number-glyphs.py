"""Developer-only: fontTools. Extract exact ASCON outlines; never rewrite letters.

Run --symbols '3+.' for the canary, then without arguments for the single sheet.
Central routes and their teaching order are authored, not prescribed by GOST.
"""
import argparse
import hashlib
import json
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
