result = {}
for character in args.symbols:
    source = '-' if character == '−' else character
    name = font.getBestCmap()[ord(source)]
    pen, bounds = SVGPathPen(glyphs), BoundsPen(glyphs)
    glyphs[name].draw(pen)
    glyphs[name].draw(bounds)
    x0,y0,x1,y1 = bounds.bounds
    model = routes[character]
    notation = [dict(offset=offset, range=span, label=label,
                     **({'dot':True} if character in '.:' else {}))
                for offset,span,label in notes[character]]
    result[character] = dict(outline=pen.getCommands(), sourceCharacter=source,
        advance=glyphs[name].width/14, bounds=[30+x0/14,30+x1/14],
        inkBounds=[30+x0/14,140-y1/14,30+x1/14,140-y0/14],
        model=model, routeSource='authored-number-centre-route',
        instruction=dict(notation=notation),
        revision=hashlib.sha256(json.dumps(model).encode()).hexdigest()[:12])
target = ROOT/'concepts/components/number-glyphs.js'
