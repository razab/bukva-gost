ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--symbols', default='0123456789+−=.,:')
args = parser.parse_args()
font_path = ROOT / 'references/isopromat-fonts/font-4.ttf'
source = json.loads((font_path.parent/'SOURCE.json').read_text())
assert hashlib.sha256(font_path.read_bytes()).hexdigest() == source['sha256'], 'Wrong source font'
font = TTFont(font_path)
glyphs = font.getGlyphSet()

# Points below use the font's own coordinates. Q segments follow the stroke core.
def route(start, *segments):
    result = [start]
    for segment in segments:
        if len(segment) == 2:
            result.append(segment)
        else:
            x, y = result[-1]
            cx, cy, ex, ey = segment
            for i in range(1, 17):
                t = i / 16
                result.append(((1-t)**2*x+2*(1-t)*t*cx+t*t*ex,
                               (1-t)**2*y+2*(1-t)*t*cy+t*t*ey))
    return [[round(30+x/14, 3), round(140-y/14, 3)] for x, y in result]

