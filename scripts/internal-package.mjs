import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const digest = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const json = value => Buffer.from(JSON.stringify(value, null, 2) + '\n');
const safePath = value => typeof value === 'string' && /^[A-Za-z0-9_./-]+$/.test(value) &&
  !value.startsWith('/') && value.split('/').every(part => part && part !== '.' && part !== '..');

async function walk(dir, prefix = '') {
  const files = [];
  for (const entry of await fs.readdir(dir, {withFileTypes: true})) {
    const name = prefix + entry.name;
    if (entry.isSymbolicLink()) throw Error('Symlink is not a bundle resource: ' + name);
    if (entry.isDirectory()) files.push(...await walk(path.join(dir, entry.name), name + '/'));
    else if (entry.isFile()) files.push(name);
    else throw Error('Unsupported resource: ' + name);
  }
  return files.sort();
}

export async function readBundle(webDir) {
  const marker = await fs.readFile(path.join(webDir, '.generated'), 'utf8');
  if (marker !== 'Generated by scripts/build-offline.mjs\n') throw Error('Unmarked offline directory');
  const script = await fs.readFile(path.join(webDir, 'precache-manifest.js'), 'utf8');
  const match = /^self\.GOST_PRECACHE=(\{.*\});\n$/.exec(script);
  if (!match) throw Error('Invalid precache manifest');
  const manifest = JSON.parse(match[1]);
  if (!/^[a-f0-9]{20}$/.test(manifest.version) || !Array.isArray(manifest.files) || !manifest.files.length)
    throw Error('Invalid bundle version or resources');
  const files = new Map(), urls = new Set();
  for (const resource of manifest.files) {
    const [name, query, extra] = String(resource.path).split('?');
    if (!safePath(name) || extra !== undefined || (query !== undefined && !/^v=\d+$/.test(query)) ||
        /(?:^|\/)(?:editor|tests|references|openspec|node_modules)(?:\/|$)|\.(?:ttf|pdf|zip)$/i.test(name))
      throw Error('Unsafe resource path: ' + resource.path);
    if (urls.has(resource.path)) throw Error('Duplicate resource URL: ' + resource.path);
    urls.add(resource.path);
    const bytes = await fs.readFile(path.join(webDir, name));
    if (crypto.createHash('sha256').update(bytes).digest('base64') !== resource.sha256)
      throw Error('Resource hash mismatch: ' + resource.path);
    files.set(name, bytes);
  }
  if (digest(Buffer.from(JSON.stringify(manifest.files))).slice(0, 20) !== manifest.version)
    throw Error('Manifest version does not match its resources');
  for (const name of ['sw.js', 'precache-manifest.js']) files.set(name, await fs.readFile(path.join(webDir, name)));
  const expected = [...files.keys(), '.generated'].sort();
  if (JSON.stringify(await walk(webDir)) !== JSON.stringify(expected)) throw Error('Files outside bundle whitelist');
  const html = files.get('index.html')?.toString();
  const build = html?.match(/name="app-build" content="(\d{4}-\d{2}-\d{2}\.\d+)"/)?.[1];
  if (!build || !html.includes('name="offline-bundle" content="true"')) throw Error('Missing offline build identity');
  for (const [, url] of html.matchAll(/(?:src|href)="([^"]+)"/g))
    if (!urls.has(url)) throw Error('HTML dependency missing from manifest: ' + url);
  return {build, version: manifest.version, resourceURLs: manifest.files.length, files};
}

export async function packageInternal({webDir = path.join(root, 'dist/web'), outputDir = path.join(root, 'dist/internal')} = {}) {
  const bundle = await readBundle(webDir);
  const source = JSON.parse(await fs.readFile(path.join(root, 'references/isopromat-fonts/SOURCE.json'), 'utf8'));
  const categories = {
    'ascon-derived': {source: source.sourcePage, originalSHA256: source.sha256, copyright: source.copyright.trim(),
      status: 'permission-unresolved', note: 'Derived glyph outlines/model. TTF is excluded; fsType=0 is not redistribution permission.'},
    'watermelon-png': {source: null, status: 'source-and-permission-unresolved', note: 'Existing approved illustration; provenance not recorded.'},
    'project-material': {source: 'Project repository', status: 'owner-confirmation-required', note: 'Project code, texts, SVG geometry and generated icons; no claim of an external licence.'}
  };
  const resources = [...bundle.files].sort(([a], [b]) => a.localeCompare(b)).map(([name, bytes]) => ({
    path: 'web/' + name, bytes: bytes.length, sha256: digest(bytes),
    category: name === 'components/glyphs.js' ? 'ascon-derived' :
      name === 'assets/watermelon-reference.png' ? 'watermelon-png' : 'project-material'
  }));
  if (!resources.some(r => r.category === 'ascon-derived') || !resources.some(r => r.category === 'watermelon-png'))
    throw Error('Resource provenance needs review after asset changes');
  const notices = {schema: 1, build: bundle.build, version: bundle.version, distribution: 'INTERNAL REVIEW ONLY', categories, resources};
  const readme = `Буквы по ГОСТ · ${bundle.build}\nINTERNAL REVIEW ONLY · Не для публичного распространения.\n\n` +
    `web/ — автономный комплект, ${bundle.resourceURLs} URL ресурсов. Для установки PWA нужны HTTPS или localhost.\n` +
    'HTTP LAN с Mac не является установленным iPad-приложением. Открытие index.html как файла не проверено.\n' +
    'Работы хранятся по origin. Перед сменой адреса сохранить копию через настройки.\n\n' +
    'Права на ASCON-контуры и PNG арбуза не подтверждены. Опись и SHA-256: RESOURCE-NOTICES.json.\n' +
    'Нет подписи/App Store-бинарного файла. Физический iPad/Pencil и проверка с детьми не выполнены.\n';
  const payload = new Map([...bundle.files].map(([name, bytes]) => ['web/' + name, bytes]));
  payload.set('RESOURCE-NOTICES.json', json(notices));
  payload.set('README-INTERNAL.txt', Buffer.from(readme));
  const name = `bukvy-po-gost-${bundle.build}-internal.zip`;
  const parent = path.join(outputDir, bundle.build);
  await fs.mkdir(parent, {recursive: true});
  const staging = await fs.mkdtemp(path.join(parent, '.package-'));
  const destination = path.join(parent, bundle.version);
  try {
    const input = path.join(staging, 'payload');
    await fs.mkdir(input);
    for (const [file, bytes] of payload) {
      await fs.mkdir(path.dirname(path.join(input, file)), {recursive: true});
      await fs.writeFile(path.join(input, file), bytes);
    }
    execFileSync('python3', [path.join(root, 'scripts/zip-internal.py'), input, path.join(staging, name)], {stdio: 'pipe'});
    const bytes = await fs.readFile(path.join(staging, name));
    const report = {schema: 1, build: bundle.build, version: bundle.version, archive: name,
      files: payload.size, resourceURLs: bundle.resourceURLs, bytes: bytes.length, sha256: digest(bytes),
      distribution: notices.distribution, unresolved: ['ASCON permission', 'Watermelon PNG provenance/permission',
        'Project ownership confirmation', 'Signed iPadOS package', 'Physical iPad/Pencil pilot', 'Publisher details']};
    await fs.writeFile(path.join(staging, name + '.sha256'), `${report.sha256}  ${name}\n`);
    await fs.writeFile(path.join(staging, 'package.json'), json(report));
    await fs.writeFile(path.join(staging, 'RESOURCE-NOTICES.json'), json(notices));
    await fs.rm(input, {recursive: true});
    try {
      await fs.rename(staging, destination);
    } catch (error) {
      if (!['EEXIST', 'ENOTEMPTY'].includes(error.code)) throw error;
      const existing = await walk(destination), prepared = await walk(staging);
      if (JSON.stringify(existing) !== JSON.stringify(prepared)) throw Error('Existing package differs; left untouched');
      for (const file of prepared) if (!(await fs.readFile(path.join(destination, file))).equals(await fs.readFile(path.join(staging, file))))
        throw Error('Existing package differs; left untouched: ' + file);
    }
    return {...report, output: destination};
  } finally {
    await fs.rm(staging, {recursive: true, force: true});
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  try {
    if (process.argv.length !== 2) throw Error('Usage: npm run package:internal (no publishing options)');
    execFileSync(process.execPath, [path.join(root, 'scripts/build-offline.mjs')], {stdio: 'inherit'});
    console.log(JSON.stringify(await packageInternal(), null, 2));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
